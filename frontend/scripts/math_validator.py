import sys
import json
import sympy
from sympy import symbols, simplify, solveset, S, Eq, latex, parse_expr

def validate_mcq(data):
    """
    Validates a Math MCQ generated by the AI.
    Expected data: {
        "type": "equation_solution" | "expression_equivalence" | "generic",
        "context": { "equation": "x**2 - 4 = 0", "variable": "x" },
        "correct_answer": "2",
        "distractors": ["0", "-2", "4"]
    }
    """
    results = {
        "is_valid": True,
        "errors": [],
        "warnings": [],
        "verified_answer": None
    }

    try:
        q_type = data.get("type", "generic")
        correct = str(data.get("correct_answer", ""))
        distractors = [str(d) for d in data.get("distractors", [])]
        context = data.get("context", {})

        if q_type == "equation_solution":
            eq_str = context.get("equation")
            var_str = context.get("variable", "x")
            
            if not eq_str:
                results["is_valid"] = False
                results["errors"].append("Missing equation in context.")
                return results

            # Standardize x**2 notation if AI used x^2
            eq_str = eq_str.replace("^", "**")
            var = symbols(var_str)
            
            # Parse equation
            if "=" in eq_str:
                lhs_str, rhs_str = eq_str.split("=")
                lhs = parse_expr(lhs_str.strip())
                rhs = parse_expr(rhs_str.strip())
                equation = Eq(lhs, rhs)
            else:
                equation = Eq(parse_expr(eq_str), 0)

            # Find all solutions
            solutions = solveset(equation, var)
            sol_list = [str(s) for s in solutions]
            
            # 1. Verify correct answer
            try:
                correct_val = parse_expr(correct.replace("^", "**"))
                if not any(simplify(correct_val - s) == 0 for s in solutions):
                    results["is_valid"] = False
                    results["errors"].append(f"Correct answer '{correct}' is NOT a solution to '{eq_str}'. Actual solutions: {sol_list}")
            except Exception as e:
                results["is_valid"] = False
                results["errors"].append(f"Failed to parse correct answer: {str(e)}")

            # 2. Check distractors for 'Two Right Answers' trap
            for d in distractors:
                try:
                    d_val = parse_expr(d.replace("^", "**"))
                    if any(simplify(d_val - s) == 0 for s in solutions):
                        results["is_valid"] = False
                        results["errors"].append(f"Distractor '{d}' is actually a correct solution! Actual solutions: {sol_list}")
                except:
                    continue # Skip distractors that aren't math-parseable

        elif q_type == "expression_equivalence":
            expr_str = context.get("expression")
            if not expr_str:
                results["is_valid"] = False
                results["errors"].append("Missing expression in context.")
                return results

            expr = parse_expr(expr_str.replace("^", "**"))
            correct_expr = parse_expr(correct.replace("^", "**"))

            # Check if correct_answer is identical under simplification
            if simplify(expr - correct_expr) != 0:
                results["is_valid"] = False
                results["errors"].append(f"Expression '{correct}' is NOT equivalent to '{expr_str}'.")

            # Check distractors
            for d in distractors:
                try:
                    d_expr = parse_expr(d.replace("^", "**"))
                    if simplify(expr - d_expr) == 0:
                        results["is_valid"] = False
                        results["errors"].append(f"Distractor '{d}' is mathematically equivalent to the target expression!")
                except: continue

        results["verified_answer"] = correct
    except Exception as e:
        results["is_valid"] = False
        results["errors"].append(f"SymPy Crash: {str(e)}")

    return results

if __name__ == "__main__":
    try:
        raw_input = sys.stdin.read()
        if not raw_input:
            print(json.dumps({"error": "No input received"}))
            sys.exit(1)
            
        input_data = json.loads(raw_input)
        result = validate_mcq(input_data)
        print(json.dumps(result))
    except Exception as e:
        print(json.dumps({"error": str(e)}))
